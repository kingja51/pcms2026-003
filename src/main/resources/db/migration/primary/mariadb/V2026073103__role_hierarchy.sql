--
--   ROLE_SUPER > ROLE_ADMIN > ROLE_MANAGER > ROLE_STAFF > ROLE_MEMBER > ROLE_REAL
--
--   · ROLE_SUPER 는 사용자가 지정한 체인에 없었으나 001 실측과 동일하게 최상위에 둔다.
