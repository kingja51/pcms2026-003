-- ── 4) 기존 관리자 계정의 role_ids 를 계층에 맞춰 재확장 ──────────────────────
--    P4 에서 역할 관리 화면이 담당할 일이지만, 그전까지는 여기서 맞춰 둔다.
UPDATE `tb_admin` a
   SET a.`role_ids` = (
        SELECT GROUP_CONCAT(h.`descendant_role_id` ORDER BY h.`depth` SEPARATOR ',')
          FROM `tb_role_hierarchy` h
          JOIN `tb_role` r ON r.`role_id` = h.`ancestor_role_id`
         WHERE r.`role_code` = a.`role_codes` AND h.`delete_yn` = 'N')
 WHERE a.`role_codes` IN ('ROLE_SUPER','ROLE_ADMIN','ROLE_MANAGER','ROLE_STAFF')
   AND a.`delete_yn` = 'N';
