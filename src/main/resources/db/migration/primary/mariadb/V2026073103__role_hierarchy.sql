--
-- tb_role_hierarchy 는 closure table 이다. 조상-자손 모든 쌍을 depth 와 함께 적재하며,
-- 자기 자신도 depth=0 으로 넣는다(001 실측 구조와 동일).
--
-- ⚠️ 이 계층을 읽어 tb_admin.role_ids 를 확장하는 코드는 아직 없다.
--    001 에서는 역할 관리 화면(RoleMngMapper)이 담당하며 003 에서는 P4 범위다.
--    그전까지 tb_admin.role_ids 는 손으로 채워야 한다.
-- ============================================================================

-- ── 1) ROLL_MANAGER → ROLE_MANAGER 오타 정정 ─────────────────────────────────
--    role_code 는 tb_admin.role_codes CSV 와 DynamicAuthorizationManager 매칭에
--    쓰이는 데이터 계약이다. 현재 이 코드를 참조하는 행이 없어 지금이 고치는 시점이다.
--    ROLL_PRIVACY 는 지시 범위 밖이라 그대로 둔다.
UPDATE `tb_role`
   SET `role_code` = 'ROLE_MANAGER'
 WHERE `role_id` = '00000000-0000-7000-8000-000000000017'
   AND `role_code` = 'ROLL_MANAGER';

